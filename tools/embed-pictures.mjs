// Builds the card pictures into index.html, keeping the app one file.
// Reads art/cards/<id>.jpg (384px JPEGs) and rewrites the block between the PICS markers.
// Run: node tools/embed-pictures.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const page = join(root, 'app/src/main/assets/index.html');
const dir = join(root, 'art/cards');
const START = '/* PICS:START — generated by tools/embed-pictures.mjs from art/cards; do not edit by hand */';
const END = '/* PICS:END */';

const files = readdirSync(dir).filter((f) => f.endsWith('.jpg')).sort();
const lines = files.map((f) =>
  ` ${JSON.stringify(f.slice(0, -4))}:"data:image/jpeg;base64,${readFileSync(join(dir, f)).toString('base64')}"`);
const block = `${START}\nconst PICS={\n${lines.join(',\n')}\n};\n${END}`;

const html = readFileSync(page, 'utf8');
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < 0) throw new Error('PICS markers not found in index.html');
writeFileSync(page, html.slice(0, a) + block + html.slice(b + END.length));
console.log(`embedded ${files.length} pictures`);
